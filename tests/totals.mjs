import assert from 'node:assert/strict';
import { summarizeUsage, isAccountLoading } from '../src/Headroom/wwwroot/usage-totals.js';
const now = Date.parse('2026-11-11T22:00:00Z'), future = now / 1000 + 600;
const quota = (remaining, minutes = 10080, bucket = 'codex') => ({ bucketId: bucket, bucket, window: minutes === 10080 ? 'Weekly' : '5-hour', windowMinutes: minutes, remaining, resetsAt: future });
const account = (id, plan, remaining, resets = 0) => ({ id, plan, email: id + '@example.com', workspaceId: 'personal-' + id,
  signedIn: true, updatedAt: new Date(now).toISOString(), error: null,
  usage: { quotas: [quota(remaining)], resetCount: resets, resets: Array.from({length: resets}, (_, i) => ({ id: id + '-' + i, resetType: 'codexRateLimits', expiresAt: future + 100 })) } });
const close = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-9, `${actual} != ${expected}`);
let accounts = [account('one', 'pro', 0), account('two', 'prolite', 47, 1), account('three', 'prolite', 6, 2)];
let result = summarizeUsage(accounts, now);
close(result.weekly, .53); close(result.banked, 3); close(result.potential, 3.53);
assert.equal(result.valuedResets, 3); assert.equal(result.resetCount, 3); assert.equal(result.partial, false);
console.log('PASS screenshot example: 0.53 remaining + up to 3 banked = 3.53 Pro 100 weekly allowances');
accounts = [account('pro', 'pro', 50, 1), account('lite', 'prolite', 50, 1), account('plus', 'plus', 50, 1), account('max', 'promax', 50, 1)];
result = summarizeUsage(accounts, now);
close(result.weekly, 4.05); close(result.banked, 8.1); close(result.potential, 12.15);
accounts[2].usage.quotas.push(quota(10, 300), quota(100, 10080, 'separate-model'));
close(summarizeUsage(accounts, now).potential, 12.15);
console.log('PASS plan weights; short windows and separate models are not double-counted');
const duplicate = {...accounts[0], id: 'duplicate', email: accounts[0].email.toUpperCase(), updatedAt: new Date(now - 1000).toISOString()};
result = summarizeUsage([...accounts, duplicate], now);
assert.equal(result.duplicates, 1); close(result.potential, 12.15);
result = summarizeUsage([...accounts, {...duplicate, workspaceId: 'another-workspace'}], now);
assert.equal(result.duplicates, 0); close(result.potential, 15.15);
console.log('PASS duplicate identities counted once; different workspaces remain separate');
accounts = [account('zero', 'prolite', 0)];
result = summarizeUsage(accounts, now); assert.equal(result.potential, 0);
accounts[0].usage.quotas[0].remaining = null;
assert.equal(summarizeUsage(accounts, now).potential, null);
accounts[0].usage.quotas[0].remaining = 50; accounts[0].error = 'Timeout';
assert.equal(summarizeUsage(accounts, now).potential, null);
accounts[0].error = null; accounts[0].updatedAt = new Date(now - 100000).toISOString();
assert.equal(summarizeUsage(accounts, now).potential, null);
accounts[0].updatedAt = null; accounts[0].signedIn = false;
result = summarizeUsage(accounts, now); assert.equal(result.pending, 1); assert.equal(result.resetCount, null);
assert.equal(isAccountLoading(accounts[0]), true);
accounts[0].error = 'Failed'; assert.equal(isAccountLoading(accounts[0]), false);
console.log('PASS loading, unknown, stale, error, and actual zero are distinct');
accounts = [account('reset', 'prolite', 20, 4)];
accounts[0].usage.resets[0].expiresAt = now / 1000 - 1;
accounts[0].usage.resets[1].resetType = 'unknown';
accounts[0].usage.resets.pop(); // truncated details: never invent the missing reset's scope
result = summarizeUsage(accounts, now);
close(result.banked, 1); close(result.potential, 1.2);
assert.equal(result.resetCount, 3); assert.equal(result.expiredResets, 1);
assert.equal(result.unvaluedResets, 2); assert.equal(result.partial, true);
accounts[0].usage.resets = null; result = summarizeUsage(accounts, now);
assert.equal(result.valuedResets, 0); assert.equal(result.unvaluedResets, 4);
assert.equal(result.banked, null); assert.equal(result.potential, null);
accounts[0].usage.resetCount = null; assert.equal(summarizeUsage(accounts, now).potential, null);
console.log('PASS expired, unknown-type, truncated, and unavailable reset details are not invented');
accounts = [account('unsupported', 'business', 90, 2), account('plus', 'plus', 50, 1)];
accounts[1].usage.quotas.push(quota(0, 300)); accounts[1].usage.ordinaryUsageAllowed = false;
accounts[1].usage.creditBalance = 25;
result = summarizeUsage(accounts, now);
close(result.potential, .15); assert.equal(result.excluded, 1); assert.equal(result.partial, true);
assert.equal(result.shortWindowBlocked, 1); assert.equal(result.permissionBlocked, 1); assert.equal(result.creditBalance, 25);
accounts[1].usage.quotas[0].resetsAt = now / 1000 - 1;
assert.equal(summarizeUsage(accounts, now).potential, null);
accounts[1].usage.quotas[0].resetsAt = future;
assert.equal(summarizeUsage([], now).potential, null);
console.log('PASS unsupported plans, binding short windows, separate credits, and due resets');
